import { z } from 'zod';

export const createRtoSchema = z.object({
  rtoName: z.string().trim().min(1, 'RTO Name is required'),
  rtoCode: z.string().trim().optional(),
  abn: z.string().trim().optional().default(''),
  acn: z.string().trim().optional().default(''),
  website: z.string().trim().optional().default(''),
  yearEstablished: z.string().trim().optional().default(''),
  shortDescription: z.string().trim().optional().default(''),
  paymentCycle: z.string().trim().optional().default('Placement'),
  payoutRate: z.coerce.number().optional().default(0),
  coursePricing: z.array(z.any()).optional().default([]),
  logo: z.string().trim().optional().default(''),
  registrationCertificate: z.string().trim().optional().default(''),
  registrationCertificateName: z.string().trim().optional().default(''),
  documents: z.array(z.any()).optional().default([]),
  contactName: z.string().trim().optional().default(''),
  contactEmail: z.string().trim().optional().default(''),
  contactTitle: z.string().trim().optional().default(''),
  contactDepartment: z.string().trim().optional().default(''),
  contactPhone: z.string().trim().optional().default(''),
  contactWhatsapp: z.string().trim().optional().default(''),
  contactMobile: z.string().trim().optional().default(''),
  contactFax: z.string().trim().optional().default(''),
  addressLine1: z.string().trim().optional().default(''),
  addressLine2: z.string().trim().optional().default(''),
  suburb: z.string().trim().optional().default(''),
  state: z.string().trim().optional().default(''),
  postcode: z.string().trim().optional().default(''),
  country: z.string().trim().optional().default('Australia'),
  partnershipSince: z.string().trim().optional().default(''),
  registrationNumber: z.string().trim().optional().default(''),
  issuingAuthority: z.string().trim().optional().default(''),
  onboardedByName: z.string().trim().optional(),
  onboardedBy: z.string().trim().nullable().optional(),
});

export const updateRtoSchema = createRtoSchema.partial();
